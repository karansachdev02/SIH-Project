/**
 * Create a translation lookup function for a given language.
 * Falls back to English if a key is missing.
 * @param {string} lang - 'en' | 'hi'
 * @returns {(key: string, fallback?: string) => string}
 */
export function createT(lang) {
  const dict = translations[lang] || translations.en
  const fallback = translations.en
  return (key, defaultValue) => {
    return dict[key] ?? fallback[key] ?? defaultValue ?? key
  }
}

